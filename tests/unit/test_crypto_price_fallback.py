"""BTC and ETH when CoinGecko refuses: the Chainlink feeds, in a fixed order.

The outage this pins down: CoinGecko's keyless `/simple/price` began answering
every caller with a CloudFront 403 HTML page while `/ping` still answered 200,
so the price tool, price alerts and ether in wallet answers all went dark.

The order: CoinGecko first only with a `COINGECKO_API_KEY`, sent as the Demo
plan header and never logged; without one, or on any CoinGecko failure, the
Chainlink feeds on Ethereum mainnet through the Infura node. Every figure is
dated by its source, a feed older than its heartbeat says it is stale, and
when both fail nothing is made up.
"""

